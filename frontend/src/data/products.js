function build(item) {
  const code = item.sku.slice(0, 5)
  const cat = catMap[code]
  const [craft, usage] = item.name.split('·')

  return {
    id: item.sku,
    sku: item.sku,
    code: item.sku,
    name: item.name,
    craft: craft || item.name,
    usage: usage || '',
    category: cat.name,
    categoryShort: cat.short,
    categoryCode: code,
    series: item.series || craft,
    price: item.price,
    size: item.size,
    capacity: item.capacity,
    material: item.material || cat.material,
    glaze: item.glaze,
    process: cat.process,
    leadTime: item.leadTime || cat.leadTime,
    stock: item.stock,
    customizable: item.customizable,
    featured: !!item.featured,
    intro: item.intro,
    story: item.story,
    note: cat.note,
    tags: [
      cat.short,
      ...(item.series === '人宠同系' ? ['人宠同系'] : []),
      ...(item.customizable ? ['可定制'] : []),
    ],
    // 每件只有一张图；以后补拍多角度，往数组里加就行
    // 大图 1200px webp，列表用 thumbs/ 里的 480px 缩略图
    images: [`/assets/products/${item.sku}.webp`],
    thumb: `/assets/products/thumbs/${item.sku}.webp`,
    ratio: '13/12',
  }
}

export const products = ITEMS.map(build)

export function findProduct(id) {
  return products.find((p) => p.id === id)
}

